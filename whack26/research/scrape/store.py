"""Document-store protocol shared by the semantic-scraping modules.

The concrete implementation is :class:`whack26.store.FieldStore`; keeping this
protocol separate means the scraping pipeline never imports SQLite directly.
"""

from __future__ import annotations

from typing import Protocol, Sequence

from .models import (
    Document,
    DocumentComparison,
    DocumentCritique,
    DocumentLink,
)


class DocumentStore(Protocol):
    def get_document(self, document_id: str) -> Document | None: ...
    def find_document_by_url(self, url_hash: str) -> Document | None: ...
    def find_document_by_content(self, content_sha512: str) -> Document | None: ...
    def upsert_document(self, document: Document) -> Document: ...
    def add_document_link(self, link: DocumentLink) -> None: ...
    def document_links(
        self, document_id: str, *, direction: str = "out"
    ) -> list[DocumentLink]: ...
    def assign_document_path(
        self, document_id: str, field_ids: Sequence[str], *, confidence: float = 1.0
    ) -> list[str]: ...
    def document_path(self, document_id: str) -> list[object]: ...
    def neighbors(self, document_id: str, limit: int = 10) -> list[Document]: ...
    def put_comparison(self, comparison: DocumentComparison) -> None: ...
    def get_comparison(
        self,
        left_id: str,
        right_id: str,
        kind: str,
        method_version: str = "1.0.0",
    ) -> DocumentComparison | None: ...
    def put_critique(self, critique: DocumentCritique) -> None: ...
    def get_critique(
        self, document_id: str, corpus_version: str
    ) -> DocumentCritique | None: ...
    def record_fetch(self, **kwargs: object) -> None: ...
    def get_fetch(self, url_hash: str) -> dict | None: ...
